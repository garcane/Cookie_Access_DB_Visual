-- Cookie Creations: core schema rebuilt from Database_for_Cookie_Creations_Database_Project.accdb
-- Run against the cookie_creations database. Re-runnable: drops and recreates everything.
--
-- Changes from the Access design:
--   * [Order] -> orders (ORDER is a reserved word); all names snake_case so nothing needs quoting.
--   * Products had two identical keys (ID and CookiesID); they are merged into product_id.
--   * DOUBLE id/count columns -> integer, CURRENCY -> numeric(10,2), DATETIME (always midnight) -> date.
--   * The Access relationships were not enforced; here they are real foreign keys.

DROP SCHEMA IF EXISTS analysis CASCADE;
DROP TABLE IF EXISTS orders, products, customers;

CREATE TABLE customers (
    customer_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    text,
    last_name     text,
    email_address text,
    phone         text,
    address       text,
    city          text,
    state         text,
    zip           text,  -- text, not a number: keeps leading zeros
    country       text,
    notes         text
);

CREATE TABLE products (
    product_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cookie_name text          NOT NULL UNIQUE,
    price       numeric(10,2) NOT NULL
);

CREATE TABLE orders (
    order_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      integer       NOT NULL REFERENCES customers (customer_id),
    product_id       integer       NOT NULL REFERENCES products (product_id),
    order_date       date          NOT NULL,
    cookies_ordered  integer       NOT NULL,
    price_per_cookie numeric(10,2) NOT NULL,
    revenue          numeric(10,2) NOT NULL,
    order_filled     boolean       NOT NULL DEFAULT false
);

CREATE INDEX orders_customer_id_idx ON orders (customer_id);
CREATE INDEX orders_product_id_idx  ON orders (product_id);
CREATE INDEX orders_order_date_idx  ON orders (order_date);

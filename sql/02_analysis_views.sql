-- Cookie Creations: analysis queries, replacing the five Access queries / xlsx exports.
-- The Access versions were plain joins with no GROUP BY or WHERE, so every export had one row
-- per order (100 rows) and the question in the name was never actually answered.
-- Each query is a view so it can be used from pgAdmin (SELECT * FROM analysis.<view>) or Power BI.
--
-- Revenue is always the stored orders.revenue (what Access and the dashboard used). Note that in the
-- source data revenue <> cookies_ordered * price_per_cookie, and price_per_cookie <> products.price.

DROP SCHEMA IF EXISTS analysis CASCADE;
CREATE SCHEMA analysis;

-- What are the total sales for each product?
CREATE VIEW analysis.total_sales_by_product AS
SELECT p.product_id,
       p.cookie_name,
       count(o.order_id)                   AS order_count,
       coalesce(sum(o.cookies_ordered), 0) AS cookies_sold,
       coalesce(sum(o.revenue), 0)         AS total_revenue
FROM products p
LEFT JOIN orders o ON o.product_id = p.product_id
GROUP BY p.product_id, p.cookie_name
ORDER BY total_revenue DESC;

-- What is the total revenue generated by each customer?
CREATE VIEW analysis.revenue_by_customer AS
SELECT c.customer_id,
       c.first_name,
       c.last_name,
       count(o.order_id)                   AS order_count,
       coalesce(sum(o.cookies_ordered), 0) AS cookies_ordered,
       coalesce(sum(o.revenue), 0)         AS total_revenue
FROM customers c
LEFT JOIN orders o ON o.customer_id = c.customer_id
GROUP BY c.customer_id, c.first_name, c.last_name
ORDER BY total_revenue DESC;

-- Which customers have placed the most orders?
CREATE VIEW analysis.customers_by_order_count AS
SELECT rank() OVER (ORDER BY count(o.order_id) DESC) AS order_rank,
       c.customer_id,
       c.first_name,
       c.last_name,
       count(o.order_id)                   AS order_count,
       coalesce(sum(o.cookies_ordered), 0) AS cookies_ordered
FROM customers c
LEFT JOIN orders o ON o.customer_id = c.customer_id
GROUP BY c.customer_id, c.first_name, c.last_name
ORDER BY order_rank, cookies_ordered DESC;

-- Which orders have not been filled?
CREATE VIEW analysis.unfilled_orders AS
SELECT o.order_id,
       o.order_date,
       c.customer_id,
       c.first_name,
       c.last_name,
       p.product_id,
       p.cookie_name,
       o.cookies_ordered,
       o.revenue
FROM orders o
JOIN customers c ON c.customer_id = o.customer_id
JOIN products  p ON p.product_id  = o.product_id
WHERE NOT o.order_filled
ORDER BY o.order_date, o.order_id;

-- What are the details of orders placed in the last month?
-- The data stops in July 2024, so "last month" is anchored on the latest month present in the data
-- rather than today's date (which would return nothing). The last order is 2024-07-16, so this is a
-- partial month (July 2024). For live data, use the previous calendar month:
--   WHERE o.order_date >= date_trunc('month', current_date) - interval '1 month'
--     AND o.order_date <  date_trunc('month', current_date)
CREATE VIEW analysis.orders_last_month AS
WITH latest AS (
    SELECT date_trunc('month', max(order_date))::date AS month_start FROM orders
)
SELECT o.order_id,
       o.order_date,
       c.customer_id,
       c.first_name,
       c.last_name,
       c.address,
       c.city,
       p.cookie_name,
       o.cookies_ordered,
       p.price AS list_price,
       o.price_per_cookie,
       o.revenue,
       o.order_filled
FROM orders o
JOIN customers c ON c.customer_id = o.customer_id
JOIN products  p ON p.product_id  = o.product_id
CROSS JOIN latest l
WHERE o.order_date >= l.month_start
  AND o.order_date <  l.month_start + interval '1 month'
ORDER BY o.order_date, o.order_id;
